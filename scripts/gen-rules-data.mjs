// Generate src/lib/rules-data.ts: the bundled ACL4SSR rule files inlined
// as a string map, so the edge function reads rules from memory instead
// of fetching them (GitHub is slow, and the ASSETS binding is not
// always reliable — both of which can get the function killed with
// HTTP 545).
//
// Only the files for the templates listed in TEMPLATES are inlined:
// inlining all 76 files (3.7MB) bloated the function bundle and made
// cold starts worse (even b64, which loads no rules, started 545ing).
// Other templates fall back to the plain same-origin fetch, then
// ASSETS, then GitHub. Keys are paths relative to ACL4SSR/Clash/
// (matching local://acl4ssr/Clash/<path>). Deterministic output
// (sorted keys) so re-running produces no diff.
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const clashDir = join(root, 'ACL4SSR', 'Clash');
// Templates to inline (the default template the site actually uses).
const TEMPLATES = ['config/ACL4SSR_WithChinaIp_WithGFW.ini'];

const files = new Set(TEMPLATES);
for (const tpl of TEMPLATES) {
  const text = await readFile(join(clashDir, tpl), 'utf8');
  for (const m of text.matchAll(/ruleset=[^,]+,(.+)/g)) {
    let res = m[1].trim().replace(/,\s*\d+\s*$/, '');
    if (res.startsWith('[]')) continue;
    if (res.startsWith('https://raw.githubusercontent.com/ACL4SSR/ACL4SSR/master/Clash/'))
      res = res.slice('https://raw.githubusercontent.com/ACL4SSR/ACL4SSR/master/Clash/'.length);
    else if (res.startsWith('rules/ACL4SSR/Clash/'))
      res = res.slice('rules/ACL4SSR/Clash/'.length);
    else continue;
    files.add(res);
  }
}
const sorted = [...files].sort();
const entries = [];
for (const rel of sorted) {
  const content = await readFile(join(clashDir, rel), 'utf8');
  entries.push(`  ${JSON.stringify(rel)}: ${JSON.stringify(content)}`);
}
const out = `// Generated by scripts/gen-rules-data.mjs. Do not edit.\n// Bundled ACL4SSR rule files (see ACL4SSR/Clash/).\nexport const RULE_FILES: Record<string, string> = {\n${entries.join(',\n')}\n};\n`;
await writeFile(join(root, 'src', 'lib', 'rules-data.ts'), out, 'utf8');
console.log(`rules-data.ts: ${sorted.length} files`);
