// Generate src/lib/rules-data.ts: the bundled ACL4SSR rule files inlined
// as a string map, so the edge function reads rules from memory instead
// of fetching them (GitHub is slow, the BlobStore is slow, and the
// ASSETS binding is unreliable on EdgeOne — all of which get the
// function killed with HTTP 545). Keys are paths relative to
// ACL4SSR/Clash/ (matching local://acl4ssr/Clash/<path>).
// Deterministic output (sorted keys) so re-running produces no diff.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const clashDir = join(root, 'ACL4SSR', 'Clash');

async function collect(dir, out = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const child = join(dir, entry.name);
    if (entry.isDirectory()) { await collect(child, out); continue; }
    if (!entry.isFile()) continue;
    if (entry.name.startsWith('._') || entry.name === '.DS_Store') continue;
    const rel = relative(clashDir, child).split('/').join('/');
    if (!(/\.ini$/i.test(entry.name) && rel.startsWith('config/')) && !/\.list$/i.test(entry.name)) continue;
    out.push(rel);
  }
  return out;
}

const files = (await collect(clashDir)).sort();
const entries = [];
for (const rel of files) {
  const content = await readFile(join(clashDir, rel), 'utf8');
  entries.push(`  ${JSON.stringify(rel)}: ${JSON.stringify(content)}`);
}
const out = `// Generated by scripts/gen-rules-data.mjs. Do not edit.\n// Bundled ACL4SSR rule files (see ACL4SSR/Clash/).\nexport const RULE_FILES: Record<string, string> = {\n${entries.join(',\n')}\n};\n`;
await writeFile(join(root, 'src', 'lib', 'rules-data.ts'), out, 'utf8');
console.log(`rules-data.ts: ${files.length} files`);
